#include "../../inc/push_swap.h"

static long	ft_atol(const char *s)
{
	long	result;
	int		sign;

	result = 0;
	sign = 1;
	while (*s == ' ' || *s == '\t' || *s == '\n' || \
*s == '\r' || *s == '\f' || *s == '\v')
		s++;
	if (*s == '-' || *s == '+')
	{
		if (*s == '-')
			sign = -1;
		s++;
	}
	while (ft_isdigit(*s))
		result = result * 10 + (*s++ - '0');
	return (result * sign);
}

static void	append_node(t_stack_node **stack, int n)
{
	t_stack_node	*node;
	t_stack_node	*last_node;

	if (!stack)
		return ;
	node = malloc(sizeof(t_stack_node));
	if (!node)
		return ;
	node->next = NULL;
	node->nbr = n;
	node->cheapest = 0;
	if (!(*stack))
	{
		*stack = node;
		node->prev = NULL;
	}
	else
	{
		last_node = find_last(*stack);
		last_node->next = node;
		node->prev = last_node;
	}
}

void	init_stack_a(t_stack_node **a, char **argv, char **split_argv)
{
	long	n;
	int		i;

	i = 0;
	while (argv[i])
	{
		if (has_syntax_error(argv[i]))
			exit_with_error(a, split_argv);
		n = ft_atol(argv[i]);
		if (n > INT_MAX || n < INT_MIN)
			exit_with_error(a, split_argv);
		if (has_duplicate(*a, (int)n))
			exit_with_error(a, split_argv);
		append_node(a, (int)n);
		i++;
	}
}

t_stack_node	*find_cheapest_node(t_stack_node *stack)
{
	if (!stack)
		return (NULL);
	while (stack)
	{
		if (stack->cheapest)
			return (stack);
		stack = stack->next;
	}
	return (NULL);
}

void	prep_stack_for_push(t_stack_node **stack,
						t_stack_node *top_node,
						char stack_name)
{
	while (*stack != top_node)
	{
		if (stack_name == 'a')
		{
			if (top_node->above_median)
				ra(stack, FALSE);
			else
				rra(stack, FALSE);
		}
		else if (stack_name == 'b')
		{
			if (top_node->above_median)
				rb(stack, FALSE);
			else
				rrb(stack, FALSE);
		}
	}
}
